// Imprime los números del 1 al 100 usando ciclo while

package Actividad_7;

public class p039_Numeros1a100 {
    public static void main(String[] args) {
        int c;
        c=1;
        while( c <= 100 ) {
            System.out.print(c+" ");
            c++;
        }
        System.out.println("\nProceso terminado ...");
    }
}